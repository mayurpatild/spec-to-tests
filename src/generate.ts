import Anthropic from '@anthropic-ai/sdk';
import type { LoadedSpec, Operation } from './spec.js';

const MODEL = process.env.CLAUDE_MODEL ?? 'claude-sonnet-4-5';

const SYSTEM = `You write Playwright API tests in TypeScript for a test engineering team.
Rules:
- Use "import { test, expect } from '@playwright/test';" and the built-in "request" fixture. No other imports.
- One test.describe per operation, titled "<METHOD> <path>".
- For every documented response status, one test that asserts the status and the shape of the body
  (check required fields and types with expect; do not pull in a schema library).
- For mutating operations add: one happy-path test with a realistic body; one test per required body
  field sending the body without it and expecting 4xx; one unauthenticated test if the operation needs auth.
- Test titles read as behaviour: "rejects a missing name with 400".
- Any ID created in a test is deleted in test.afterEach, even when the test failed.
- Never use fixed sleeps. Never hard-code the host; rely on baseURL.
- If an endpoint cannot be exercised without data you do not have, write the test with test.fixme and a one-line reason.
Output only the TypeScript file content, no prose, no markdown fences.`;

export interface GenerateOptions {
  spec: LoadedSpec;
  tag: string;
  ops: Operation[];
  client?: Anthropic;
}

export function buildPrompt(spec: LoadedSpec, tag: string, ops: Operation[]): string {
  const trimmed = ops.map(o => ({
    method: o.method.toUpperCase(), path: o.path, summary: o.summary, security: o.security, kind: o.kind,
    params: o.params, requestBody: o.requestBody, responses: o.responses,
  }));
  return `API: ${spec.title} v${spec.version}\nTag: ${tag}\nOperations (JSON):\n${JSON.stringify(trimmed, null, 1)}`;
}

/** Ask Claude for one spec file covering all operations in a tag. */
export async function generateTagFile(opts: GenerateOptions): Promise<string> {
  const client = opts.client ?? new Anthropic();
  const res = await client.messages.create({
    model: MODEL,
    max_tokens: 8000,
    system: SYSTEM,
    messages: [{ role: 'user', content: buildPrompt(opts.spec, opts.tag, opts.ops) }],
  });
  const text = res.content.filter(b => b.type === 'text').map(b => (b as any).text).join('\n').trim();
  return stripFences(text);
}

export function stripFences(s: string): string {
  return s.replace(/^```(?:ts|typescript)?\s*/i, '').replace(/```\s*$/, '').trim() + '\n';
}

export function header(spec: LoadedSpec, source: string): string {
  return `// Generated by spec-to-tests from ${source}\n// spec: ${spec.title} v${spec.version} (${spec.hash})\n// Regenerate instead of editing; put hand-written scenarios in tests/scenarios/.\n\n`;
}
